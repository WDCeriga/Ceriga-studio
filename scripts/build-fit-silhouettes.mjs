// Generates src/app/components/builder/design-system/fitSilhouettes.ts from the traced fit thumbnails.
// The traces share one coordinate space; the generated module keeps that space so fits compare at true scale.
// Usage: node scripts/build-fit-silhouettes.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import simplify from 'simplify-js';

const FITS = ['slim', 'regular', 'boxy', 'oversized'];
const toPoints = d => [...d.matchAll(/(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)/g)].map(m => ({ x: +m[1], y: +m[2] }));
const toPath = pts => 'M' + pts.map(p => `${p.x.toFixed(1)},${p.y.toFixed(1)}`).join('L') + 'Z';
const out = {}; let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
for (const fit of FITS) {
  const svg = readFileSync(`src/assets/studio-tshirt/fit-thumbnails/${fit}.svg`, 'utf8');
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(m => m[1]);
  const [outer, ...inner] = paths.map(d => simplify(toPoints(d), 1.6, true));
  for (const p of outer) { minX = Math.min(minX, p.x); maxX = Math.max(maxX, p.x); minY = Math.min(minY, p.y); maxY = Math.max(maxY, p.y); }
  out[fit] = { outer: toPath(outer), details: inner.map(pts => 'M' + pts.map(p => `${p.x.toFixed(1)},${p.y.toFixed(1)}`).join('L')) };
}
const pad = 30;
const viewBox = [minX - pad, minY - pad, maxX - minX + pad * 2, maxY - minY + pad * 2].map(n => +n.toFixed(1)).join(' ');
const body = `// Generated by scripts/build-fit-silhouettes.mjs from src/assets/studio-tshirt/fit-thumbnails/*.svg. Do not edit.
// All fits share one coordinate space (viewBox below), so silhouettes compare at true relative size.
export type FitSilhouetteId = ${FITS.map(f => `'${f}'`).join(' | ')};
export const FIT_SILHOUETTE_VIEWBOX = '${viewBox}';
export const FIT_SILHOUETTES: Record<FitSilhouetteId, { outer: string; details: string[] }> = ${JSON.stringify(out, null, 1)};
`;
writeFileSync('src/app/components/builder/design-system/fitSilhouettes.ts', body);
console.log(`viewBox ${viewBox}; sizes`, Object.fromEntries(FITS.map(f => [f, out[f].outer.length])));
