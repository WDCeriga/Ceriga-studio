  const zone=page.locator('[data-print-design-zone]');
  const assets=()=>page.getByRole('button',{name:'Assets',exact:true}).click();
  await assets();await page.getByRole('button',{name:'+ Create Asset',exact:true}).click();
  await page.getByRole('textbox',{name:'Asset name',exact:true}).fill('Editable typography');
  await page.getByRole('button',{name:'Typography',exact:true}).click();
  await page.getByRole('textbox',{name:'Type, then add',exact:true}).fill('CERIGA');
  await page.getByRole('button',{name:'Add',exact:true}).click();
  const panel=page.locator('[data-text-effects-panel]');
  await panel.locator('summary').click();
  assert.equal(await panel.getByRole('button',{name:/^Add .* effect$/}).count(),34);
  assert.equal(await panel.locator('canvas').count(),34);
  const add=name=>panel.getByRole('button',{name:`Add ${name} effect`,exact:true}).click();
  const ready=async()=>{try{await page.waitForFunction(()=>!document.querySelector('[data-print-design-zone] [data-text-effects-pending="true"]'),{},{timeout:30000});}catch(error){console.error(await zone.locator('[data-text-effects]').evaluateAll(nodes=>nodes.map(node=>({error:node.getAttribute('data-text-effects-error'),html:node.outerHTML.slice(0,1800)}))));throw error;}};
  const pixels=()=>zone.locator('[data-text-effects-canvas]').first().evaluate(canvas=>canvas.toDataURL());
  await add('Chrome');await ready();
  const full=await pixels();
  await panel.getByLabel('Effect intensity',{exact:true}).fill('35');await ready();
  assert.notEqual(await pixels(),full,'Live input changes rendered effect');
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  assert.equal(await panel.getByLabel('Effect intensity',{exact:true}).inputValue(),'100');
  await page.getByRole('button',{name:'Redo',exact:true}).click();
  assert.equal(await panel.getByLabel('Effect intensity',{exact:true}).inputValue(),'35');
  await add('Distressed');await ready();
  const worn=await pixels();
  await panel.getByRole('button',{name:'Randomise',exact:true}).click();await ready();
