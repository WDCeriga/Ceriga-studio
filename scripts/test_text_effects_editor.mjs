  await layer.locator('[data-text-effects]').dblclick();
  const editor=layer.locator('textarea');await editor.fill('COLLECTION 01');await editor.press('Tab');
  await ready();
  assert.equal(await layer.locator('[data-text-effects-canvas]').getAttribute('aria-label'),'COLLECTION 01');
  await page.getByRole('slider',{name:'Curve amount',exact:true}).fill('65');await ready();
  assert((await layer.locator('textPath').count())>0,'Curved source remains live and editable');
  await page.getByRole('button',{name:'Save Asset',exact:true}).click();
  await page.locator('[data-asset-artboard]').waitFor({state:'detached'});
  await assets();await page.getByRole('button',{name:'Edit Asset',exact:true}).click();
  await zone.locator('[data-print-id]').first().click();
  await page.getByRole('button',{name:'Typography',exact:true}).click();
  await panel.locator('summary').click();
  assert.equal(await panel.getByRole('button',{name:/^Edit .* effect \d+$/}).count(),3,'Saved source keeps effects stack');
  await ready();
  assert.equal(await zone.locator('[data-text-effects-canvas]').getAttribute('aria-label'),'COLLECTION 01');
  await page.getByRole('button',{name:'← Back to Garment',exact:true}).click();
  await page.getByRole('button',{name:'Typography',exact:true}).click();
  await page.getByRole('textbox',{name:'Type, then add',exact:true}).fill('FRONT');
  await page.getByRole('button',{name:'Add',exact:true}).click();
  await panel.locator('summary').click();await add('Chrome');await ready();
  await page.getByRole('button',{name:'Duplicate',exact:true}).first().click();await ready();
  assert.equal(await zone.locator('[data-text-effects-canvas]').count(),2,'Duplicate retains editable effects');
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  await page.getByRole('button',{name:/^back$/i}).last().click();
