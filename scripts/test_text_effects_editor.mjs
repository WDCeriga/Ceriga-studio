  await panel.getByLabel('Effect Depth',{exact:true}).fill('24');await ready();
  const stacked=await pixels();
  await panel.getByRole('button',{name:'Move 3D / Extrude effect 3 up',exact:true}).click();await ready();
  assert.notEqual(await pixels(),stacked);
  await panel.getByRole('button',{name:'Hide Chrome effect 1',exact:true}).click();
  assert.equal(await panel.getByRole('button',{name:'Show Chrome effect 1',exact:true}).count(),1);
  await panel.getByRole('button',{name:'Show Chrome effect 1',exact:true}).click();
  await panel.getByRole('button',{name:'Duplicate Chrome effect 1',exact:true}).click();
  assert.equal(await panel.getByRole('button',{name:/^Edit .* effect \d+$/}).count(),4);
  await panel.getByRole('button',{name:'Remove Chrome effect 2',exact:true}).click();
  await add('Gradient');
  await panel.getByLabel('Effect Gradient Type',{exact:true}).selectOption('conic');
  await panel.getByRole('button',{name:'Add stop',exact:true}).click();
  assert.equal(await panel.getByLabel('Stop 3 colour',{exact:true}).count(),1);
  await panel.getByLabel('Stop 3 colour',{exact:true}).fill('#44ee66');
  await panel.getByLabel('Stop 3 position',{exact:true}).fill('65');
  await panel.getByRole('button',{name:'Remove Gradient effect 4',exact:true}).click();
  await add('Image Fill');
  const svg=Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64"><path fill="#e30" d="M0 0h32v64H0z"/><path fill="#38f" d="M32 0h32v64H32z"/></svg>');
  await panel.getByLabel('Upload fill image',{exact:true}).setInputFiles({name:'fill.svg',mimeType:'image/svg+xml',buffer:svg});
  await panel.locator('img[alt="Current fill source"]').waitFor();await ready();
