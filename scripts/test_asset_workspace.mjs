  await page.getByRole('dialog').getByRole('button', { name: 'Save Asset', exact: true }).click();
  await page.locator('[data-asset-artboard]').waitFor({ state: 'detached', timeout: 30000 });
  assert.equal(await zone.locator(`[data-print-id="${backId}"]`).count(), 1);
  const placed = zone.locator('[data-print-id^="asset-"]');
  await placed.waitFor();
  assert.equal(await placed.locator('[data-handles]').count() > 0, true);
  const png = await placed.locator('img').getAttribute('src');
  const { data, info } = await sharp(Buffer.from(png.split(',')[1], 'base64')).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  assert.equal(info.width, 900); assert.equal(info.height, 600);
  assert.equal(data[3], 0, 'Canvas background remains transparent');
  assert(data.some((v, i) => i % 4 === 3 && v > 0), 'Export contains artwork');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  assert.equal(await zone.locator('[data-print-id^="asset-"]').count(), 0);
  assert.equal(await zone.locator(`[data-print-id="${backId}"]`).count(), 1);
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
