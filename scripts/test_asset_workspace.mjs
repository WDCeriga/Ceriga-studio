  await drop('rect');
  await page.waitForFunction(async () => (await (await import('/src/app/lib/assetLibraryStorage.ts')).readStoredAssets('asset-draft:guest')).length === 1);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.waitForFunction(async () => (await (await import('/src/app/lib/assetLibraryStorage.ts')).readStoredAssets('asset-draft:guest')).length === 0);
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await page.waitForFunction(async () => (await (await import('/src/app/lib/assetLibraryStorage.ts')).readStoredAssets('asset-draft:guest')).length === 1);
  await page.reload();
  for (let step = 0; step < 10 && !await page.getByRole('button', { name: 'Continue to Review', exact: true }).isVisible(); step++) await page.getByRole('button', { name: 'Continue', exact: true }).first().click();
