  await page.getByRole('button', { name: 'Save Asset', exact: true }).click();
  await page.locator('header [role="alert"]').waitFor();
  assert.equal(await page.locator('[data-asset-artboard]').count(), 1, 'Failed save keeps editable document');
  await page.locator('[data-test-broken-image]').evaluate(node => node.remove());
  await page.getByRole('button', { name: 'Save Asset', exact: true }).click();
