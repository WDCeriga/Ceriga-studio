  assert.equal(await page.getByRole('button', { name: 'Edit Asset', exact: true }).count(), 3, 'Saved library survives reload');
  await page.getByRole('button', { name: 'Resume asset draft', exact: true }).click();
  assert.equal(await zone.locator(':scope > [data-print-id]').count(), 1, 'Unfinished source survives reload');
  await page.getByRole('button', { name: '← Back to Garment', exact: true }).click();
  await page.getByRole('button', { name: 'Discard Changes', exact: true }).click();
  await page.locator('[data-asset-artboard]').waitFor({ state: 'detached' });
  await assets();
  await page.getByRole('button', { name: 'Edit Asset', exact: true }).first().click();
