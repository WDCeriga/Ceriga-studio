  await page.getByRole('button', { name: 'Duplicate', exact: true }).first().click();
  assert.equal(await zone.locator(':scope > [data-print-id]').count(), 2);
  const childIds = await zone.locator('[data-group-child]').evaluateAll(nodes => nodes.map(node => node.dataset.groupChild));
  assert.equal(new Set(childIds).size, 4, 'Duplicated groups have unique child rendering IDs');
  await page.getByRole('button', { name: 'Delete layer', exact: true }).first().click();
  assert.equal(await zone.locator(':scope > [data-print-id]').count(), 1);
  await page.getByRole('button', { name: 'Save Asset', exact: true }).click();
  await page.getByRole('dialog', { name: 'Asset Name', exact: true }).waitFor();
