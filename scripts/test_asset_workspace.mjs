  await page.getByRole('button', { name: 'Place Test graphic', exact: true }).evaluate(button => {
    const dataTransfer = new DataTransfer();
    button.dispatchEvent(new DragEvent('dragstart', { bubbles: true, dataTransfer }));
    const target = document.querySelector('[data-print-design-zone]');
    const box = target.getBoundingClientRect();
    target.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer, clientX: box.x + box.width * .4, clientY: box.y + box.height * .5 }));
  });
