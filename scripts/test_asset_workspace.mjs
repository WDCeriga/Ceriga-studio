  assert.equal(await page.getByRole('button', { name: 'Save Changes', exact: true }).isVisible(), true);
  assert.equal(await page.getByRole('button', { name: '← Back to Garment', exact: true }).isVisible(), true);
  assert.equal(await page.getByRole('button', { name: /^front$/i }).count(), 0);
  await page.getByRole('button', { name: '← Back to Garment', exact: true }).click();
