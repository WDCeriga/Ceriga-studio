    const box = node.getBoundingClientRect(); const dataTransfer = new DataTransfer();
    dataTransfer.setData('application/x-ceriga-asset', JSON.stringify({ kind: args.kind, id: args.id }));
    node.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer, clientX: box.x + box.width * args.fraction, clientY: box.y + box.height * .5 }));
