import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { asAccount, testDatabase } from './support/testDatabase.mjs';

const db = await testDatabase();
try {
  await db.exec(await fs.readFile('supabase/migrations/20261111010000_separate_team_management.sql', 'utf8'));
  await db.exec(await fs.readFile('supabase/migrations/20261111020000_retire_manual_team_invites.sql', 'utf8'));
  const owner = '11111111-1111-1111-1111-111111111111';
  const other = '22222222-2222-2222-2222-222222222222';
  const admin = '33333333-3333-3333-3333-333333333333';
  const member = '44444444-4444-4444-4444-444444444444';
  const viewer = '55555555-5555-5555-5555-555555555555';
  const emails = new Map([[owner,'factory@fixture.invalid'],[other,'other@fixture.invalid'],[admin,'owner@ceriga.io'],[member,'member@fixture.invalid'],[viewer,'viewer@fixture.invalid']]);
  for (const [id,email] of emails) await db.query('insert into auth.users(id,email,email_confirmed_at) values ($1,$2,now())',[id,email]);
  await db.query("insert into manufacturer_profiles(user_id,factory_name,status,onboarding_complete) values ($1,'Factory A','active',true),($2,'Factory B','active',true)",[owner,other]);
  const as = id => asAccount(db,id,emails.get(id));
  const rpc = async (name,args=[]) => (await db.query('select public.'+name+'('+args.map((_,i)=>'$'+(i+1)).join(',')+') as result',args)).rows[0].result;
  const issue = async (...args) => {
    await db.exec('reset role;set role service_role');
    return rpc('issue_workspace_invitation',args);
  };
  await as(owner);
  await assert.rejects(()=>rpc('factory_team_invite',[emails.get(member),'staff']),/permission denied/);
  await assert.rejects(()=>rpc('issue_workspace_invitation',[owner,false,emails.get(member),'Name','staff',owner]),/permission denied/);
  await assert.rejects(()=>rpc('platform_worker_management'),/access denied/);
  await assert.rejects(()=>rpc('admin_factory_team',[other]),/access denied/);
  await assert.rejects(()=>issue(owner,false,emails.get(member),'Name','staff',other),/cannot grant/);
  await assert.rejects(()=>issue(owner,true,emails.get(member),'Name','staff'),/Internal team invitation permission/);
  const factory = await issue(owner,false,emails.get(member),'Factory Member','staff',owner);
  await assert.rejects(()=>issue(owner,false,emails.get(member),'Name','staff',owner),/pending invitation/);
  await assert.rejects(()=>issue(owner,false,emails.get(member),'Name','owner',owner),/valid email and role/);
  assert.equal(await rpc('finish_workspace_invitation_delivery',[false,factory.id,factory.revision,false]),true);
  const resent = await issue(owner,false,emails.get(member),null,'staff',owner,factory.id);
  assert.equal(await rpc('finish_workspace_invitation_delivery',[false,factory.id,factory.revision,true]),false);
  assert.equal(await rpc('finish_workspace_invitation_delivery',[false,resent.id,resent.revision,true]),true);
  await as(other);
  assert.equal((await rpc('factory_team_list')).invitations.length,0);
  await assert.rejects(()=>rpc('accept_factory_invitation',[resent.token]),/verified invited email/);
  await as(member);
  await assert.rejects(()=>rpc('accept_factory_invitation',[factory.token]),/expired|used/i);
  assert.equal(await rpc('accept_factory_invitation',[resent.token]),owner);
  await assert.rejects(()=>rpc('accept_factory_invitation',[resent.token]),/expired|used/i);
  await as(admin);
  const staff = (await rpc('admin_factory_team',[owner])).members.find(row=>row.email===emails.get(member));
  assert.equal(staff.name,'Factory Member');
  assert.equal((await rpc('admin_factory_team',[other])).members.some(row=>row.email===emails.get(member)),false);
  assert.equal((await rpc('platform_worker_management')).workers.length,0);
  const role = await rpc('platform_worker_manage',['save_role',{name:'Factory oversight',permissions:{'manufacturer_teams.view':'all'}}]);
  const invite = await issue(admin,true,emails.get(member),'Ceriga Member',role.id);
  await as(member);
  await rpc('accept_platform_worker_invitation',[invite.token]);
  await assert.rejects(()=>rpc('accept_platform_worker_invitation',[invite.token]),/expired|used/i);
  assert.equal((await rpc('admin_factory_team',[owner])).canManage,false);
  await assert.rejects(()=>rpc('admin_change_factory_team',[owner,staff.id,staff.revision,'sales',false]),/management permission/);
  await as(admin);
  await assert.rejects(()=>rpc('admin_change_factory_team',[other,staff.id,staff.revision,'sales',false]),/Member changed/);
  await rpc('admin_change_factory_team',[owner,staff.id,staff.revision,'sales',false]);
  const internal = (await rpc('platform_worker_management')).workers;
  assert.equal(internal.length,1);
  assert.equal(internal[0].member_name,'Ceriga Member');
  assert.equal((await rpc('admin_factory_team',[owner])).members.find(row=>row.id===staff.id).role,'sales');
  await assert.rejects(()=>rpc('platform_worker_manage',['remove',{user_id:member,revision:internal[0].revision}]),/Disable this member/);
  await rpc('platform_worker_manage',['suspend',{user_id:member,revision:internal[0].revision}]);
  const disabled = (await rpc('platform_worker_management')).workers[0];
  assert.equal(disabled.status,'suspended');
  await rpc('platform_worker_manage',['remove',{user_id:member,revision:disabled.revision}]);
  assert.equal((await rpc('platform_worker_management')).workers.length,0);
  assert.equal((await rpc('admin_factory_team',[owner])).members.find(row=>row.id===staff.id).status,'Active');
  await as(member);
  assert.equal((await rpc('platform_worker_context')).status,'none');
  assert.equal((await rpc('factory_team_context')).factoryId,owner);
  console.log('PASS workspace invitation isolation, delivery revisions, existing-account activation, replay and oversight permission');
} catch (error) {
  console.error(error.message, error.where ?? '');
  process.exitCode=1;
} finally { await db.close(); }
