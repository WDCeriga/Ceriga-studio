import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {testDatabase,asAccount} from './support/testDatabase.mjs';
import {selectTestShipping,verifyTestPayment} from './support/shippingFixture.mjs';
const db=await testDatabase();
const [admin,buyer,a,b,outsider]=Array.from({length:5},()=>randomUUID());
const call=async(sql,args=[]) => (await db.query(sql,args)).rows[0]?.value;
try {
 for(const id of [admin,buyer,a,b,outsider]) await db.query('insert into auth.users(id,email) values($1,$2)',[id,id===admin?'owner@ceriga.io':id+'@example.invalid']);
 for(const id of [a,b,outsider]) await db.query("insert into public.manufacturer_profiles(user_id,factory_name,status,onboarding_complete,garments) values($1,$2,'active',true,array['T-shirts'])",[id,id]);
 await db.query("update public.profiles set preferred_currency='GBP' where id in ($1,$2,$3)",[a,b,buyer]);
 await asAccount(db,buyer);
 const order=(await call('select public.create_customer_order($1) value',[{kind:'production',product_name:'Private order',garment_type:'T-shirts',contact_name:'Private person',delivery_address:{country:'GB'},order_quantities:{mode:'custom_clothing',sample:{id:'sample',kind:'sample',bySize:{m:2}},bulkRuns:[]}}])).id;
 await asAccount(db,admin,'owner@ceriga.io');
 const request=(first,second)=>call('select public.admin_request_factory_comparison($1,$2,$3,current_date+2,current_date+3) value',[order,first,second]);
 await assert.rejects(request(a,a),/different/);
 await request(a,b);
 const compare=()=>call('select public.admin_factory_comparisons() value');
 assert.deepEqual((await compare()).map(x=>x.status),['pending','pending']);
 const inbox=()=>call('select public.factory_comparison_requests() value');
 const quote=(price,comments)=>call('select public.factory_respond_comparison($1,$2,$3) value',[order,JSON.stringify([{id:'sample',currency:'GBP',unitPriceCents:price,leadTimeDays:5,shipping:{priceCents:100,currency:'GBP',provider:'Carrier',method:'Road',origin:'PT',destination:'GB'}}]),comments]);
 await asAccount(db,outsider);
 assert.deepEqual(await inbox(),[]);
 await assert.rejects(quote(999,'Private'),/unavailable/);
 await asAccount(db,a);
 assert.equal((await inbox())[0].assigned_manufacturer_id,a);
 assert.doesNotMatch(JSON.stringify(await inbox()),/Private person/);
 await assert.rejects(compare(),/Superadmin/);
 await quote(200,'A only');
 await asAccount(db,b);
 assert.deepEqual((await inbox())[0].manufacturer_quote,[]);
 await quote(300,'B only');
 await asAccount(db,admin,'owner@ceriga.io');
 const offers=await compare();
 assert.equal(offers.find(x=>x.factoryId===a).tiers[0].manufacturerQuoteCents,400);
 assert.equal(offers.find(x=>x.factoryId===b).comments,'B only');
 const pick=(id)=>call('select public.admin_select_factory_quote($1,$2,$3) value',[order,id,'Reviewed']);
 await pick(a);
 await pick(b);
 assert.equal((await compare()).find(x=>x.status==='selected').factoryId,b);
 await selectTestShipping(db,order);
 await call('select public.publish_order_quote($1,$2) value',[order,JSON.stringify([{id:'sample',cents:900}])]);
 assert.equal(await call("select status value from public.order_factory_quotes where order_id=$1 and factory_id=$2",[order,a]),'not_selected');
 assert.equal(await call('select production_released_at value from public.account_orders where id=$1',[order]),null);
 await verifyTestPayment(db,order,'sample');
 assert.equal(await call('select assigned_manufacturer_id value from public.account_orders where id=$1',[order]),b);
 assert.ok(await call('select production_released_at value from public.account_orders where id=$1',[order]));
 await asAccount(db,a);
 assert.equal(await call('select count(*)::int value from public.account_orders where id=$1',[order]),0);
 await asAccount(db,buyer);
 await assert.rejects(call('select public.factory_respond_comparison($1,$2,$3) value',[order,'[]','bad']),/access denied/);
 const second=(await call('select public.create_customer_order($1) value',[{kind:'production',product_name:'Expiry fixture',garment_type:'T-shirts',order_quantities:{mode:'custom_clothing',sample:{id:'sample',kind:'sample',bySize:{m:1}},bulkRuns:[]}}])).id;
 await asAccount(db,admin,'owner@ceriga.io');
 await call('select public.admin_request_factory_comparison($1,$2,$3,current_date+2,current_date+3)',[second,a,b]);
 await db.query('update public.order_factory_quotes set due_on=current_date-1 where order_id=$1 and factory_id=$2',[second,b]);
 await asAccount(db,a);
 await call('select public.factory_respond_comparison($1,$2,$3,true)',[second,'[]','Unavailable this week']);
 await asAccount(db,b);
 await assert.rejects(call('select public.factory_respond_comparison($1,$2,$3,true)',[second,'[]','Too late']),/expired/);
 await asAccount(db,admin,'owner@ceriga.io');
 assert.deepEqual((await compare()).filter(x=>x.orderId===second).map(x=>x.status).sort(),['declined','expired']);
 console.log('PASS dual requests, incomplete comparison, two submissions, switching preferred manufacturer and factory privacy');
} catch(error){console.error(error.message,error.where??'');process.exitCode=1;}
finally{await db.close();}
