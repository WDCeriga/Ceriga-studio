import assert from 'node:assert/strict';
import {surfaceRuntime} from '../scripts/surface-test-runtime.mjs';
const {api}=await surfaceRuntime("export * from './src/app/lib/labelColourSections'; export * from './src/app/lib/surfaceMigration'; export * from './src/app/lib/surfaceDocumentEditing'; export * from './src/app/data/garmentLabels';");
const label=api.createGarmentLabel('neck'),initial=api.readLabelSurface(label);
const result=api.addLabelColourSection(initial,'top'),value=result.value;
const section=value.document.elements.find(element=>element.id===result.id);
assert.equal(section.width,value.surface.width);
assert.equal(section.borderWidth,0);
const text=value.document.elements.find(element=>element.type==='text'&&element.y<value.surface.height/3);
assert(text);
assert(value.document.elements.indexOf(section)<value.document.elements.indexOf(text));
assert.notEqual(text.frameId,result.id);
const movedSection={...section,y:section.y+3};
const moved=api.editSurfaceDocument(value,value.document.elements.map(element=>element.id===section.id?movedSection:element));
assert.equal(moved.elements.find(element=>element.id===text.id).y,text.y);
const linked={...value,document:{...value.document,elements:value.document.elements.map(element=>element.id===text.id?{...element,frameId:section.id,followSection:true}:element),frames:value.document.frames.map(frame=>frame.id===section.id?{...frame,artworks:[section.id,text.id]}:frame)}};
const movedLinked=api.editSurfaceDocument(linked,linked.document.elements.map(element=>element.id===section.id?movedSection:element));
assert.equal(movedLinked.elements.find(element=>element.id===text.id).y,text.y+3);
const fold=value.document.elements.find(element=>element.svgPrecision?.parents.some(parent=>'data-label-fabric' in parent.attrs)&&element.svgPrecision.parents.some(parent=>'opacity' in parent.attrs));
assert(fold);
assert(value.document.elements.indexOf(fold)>value.document.elements.indexOf(section));
const deleted=api.editSurfaceDocument(value,value.document.elements.filter(element=>element.id!==result.id));
assert(deleted.elements.some(element=>element.id===text.id));
assert.equal(deleted.elements.find(element=>element.id===text.id).frameId,text.frameId);
assert(!deleted.frames.some(frame=>frame.id===result.id));
assert.deepEqual(deleted.elements.filter(element=>element.surfaceRole==='border'),value.document.elements.filter(element=>element.surfaceRole==='border'));
console.log('PASS: text moves independently by default, explicit section links move together, and fold shading stays above colour');
